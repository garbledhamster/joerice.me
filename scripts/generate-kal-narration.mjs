import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import {
	mkdir,
	mkdtemp,
	readFile,
	rm,
	rmdir,
	writeFile,
} from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { promisify } from "node:util";
import { portfolioNarrationLines } from "../assets/js/folder/kal-tour.js";

const [dependencyFolder, ffmpeg = "ffmpeg", builderWelcome] =
	process.argv.slice(2);
if (!dependencyFolder) {
	throw new Error(
		"Usage: node scripts/generate-kal-narration.mjs <Kokoro npm prefix> [ffmpeg executable] [Builder welcome m4a]",
	);
}
const require = createRequire(join(resolve(dependencyFolder), "package.json"));
const { KokoroTTS } = require("kokoro-js");
const model = "onnx-community/Kokoro-82M-v1.0-ONNX";
const voice = "am_michael";
const speed = 0.94;
const run = promisify(execFile);
const assetFolder = new URL("../assets/audio/kal/", import.meta.url);
const manifest = new URL(
	"../assets/js/folder/kal-narration-tracks.js",
	import.meta.url,
);
const work = await mkdtemp(join(tmpdir(), "portfolio-kal-"));

function pcmWave(samples) {
	const sampleRate = 24_000;
	const wave = Buffer.alloc(44 + samples.length * 2);
	wave.write("RIFF", 0);
	wave.writeUInt32LE(wave.length - 8, 4);
	wave.write("WAVEfmt ", 8);
	wave.writeUInt32LE(16, 16);
	wave.writeUInt16LE(1, 20);
	wave.writeUInt16LE(1, 22);
	wave.writeUInt32LE(sampleRate, 24);
	wave.writeUInt32LE(sampleRate * 2, 28);
	wave.writeUInt16LE(2, 32);
	wave.writeUInt16LE(16, 34);
	wave.write("data", 36);
	wave.writeUInt32LE(samples.length * 2, 40);
	for (const [index, sample] of samples.entries()) {
		wave.writeInt16LE(
			Math.round(Math.min(1, Math.max(-1, sample)) * 32767),
			44 + index * 2,
		);
	}
	return wave;
}

try {
	const tts = await KokoroTTS.from_pretrained(model, {
		device: "cpu",
		dtype: "q8",
	});
	const wave = join(work, "line.wav");
	const encoded = join(work, "line.m4a");
	const tracks = {};
	await mkdir(assetFolder, { recursive: true });
	for (const [id, line] of Object.entries(portfolioNarrationLines())) {
		let clip;
		if (id === "welcome" && builderWelcome) {
			clip = await readFile(builderWelcome);
		} else {
			const audio = await tts.generate(line, { voice, speed });
			if (audio.sampling_rate !== 24_000 || !audio.audio.length) {
				throw new Error(`Unexpected narration output for ${id}.`);
			}
			await writeFile(wave, pcmWave(audio.audio));
			await run(ffmpeg, [
				"-hide_banner",
				"-loglevel",
				"error",
				"-y",
				"-i",
				wave,
				"-c:a",
				"aac",
				"-b:a",
				"48k",
				"-movflags",
				"+faststart",
				encoded,
			]);
			clip = await readFile(encoded);
		}
		const hash = createHash("sha256").update(clip).digest("hex").slice(0, 12);
		const name = `${id}-${hash}.m4a`;
		await writeFile(new URL(name, assetFolder), clip);
		tracks[line] = name;
		console.log(`${name} (${clip.length} bytes)`);
	}
	await writeFile(
		manifest,
		`// Generated by scripts/generate-kal-narration.mjs using Kokoro am_michael at 0.94.\nexport const kalNarrationTracks = ${JSON.stringify(tracks, null, "\t")};\n`,
	);
} finally {
	for (const file of ["line.wav", "line.m4a"]) {
		await rm(join(work, file), { force: true });
	}
	await rmdir(work);
}
